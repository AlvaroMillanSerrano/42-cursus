def _build() -> dict[str, list[tuple[int, int, int]]]:
    """Convert the ASCII art to horizontal runs ``(col, row, length)``."""
    glyphs: dict[str, list[tuple[int, int, int]]] = {" ": []}
    for block in _ART.strip().split("\n\n"):
        lines = block.split("\n")
        char, rows = lines[0], lines[1:]
        if len(rows) != GLYPH_H or any(len(r) != GLYPH_W for r in rows):
            raise ValueError(f"malformed glyph {char!r}")
        runs: list[tuple[int, int, int]] = []
        for row, line in enumerate(rows):
            col = 0
            while col < GLYPH_W:
                if line[col] == "#":
                    start = col
                    while col < GLYPH_W and line[col] == "#":
                        col += 1
                    runs.append((start, row, col - start))
                else:
                    col += 1
        glyphs[char] = runs
    return glyphs


GLYPHS = _build()
